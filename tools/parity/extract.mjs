// Extracts the geometry engine out of the reverse-engineered bundle into a
// standalone module, so the Rust port can be diffed against the original.
//
// Source: /tmp/opencode/recon-logofx/pretty-CreateX-BY5jD11_.js, produced by
// prettier over assets/CreateX-BY5jD11_.js (the deployed studio bundle).
//
// Two slices, because the React hook between them (lines 658-939) needs React:
//   141-653  constants, primitives, grid table, refit table, face builder
//   940-1013 tile addressing and transforms
import fs from 'node:fs';
import path from 'node:path';

const SRC = process.env.RECON_SRC ?? '/tmp/opencode/recon-logofx/pretty-CreateX-BY5jD11_.js';
const OUT = path.join(import.meta.dirname, 'engine.mjs');

const lines = fs.readFileSync(SRC, 'utf8').split('\n');
const slice = (from, to) => lines.slice(from - 1, to).join('\n');

const geometry = slice(141, 653);
const tiling = slice(940, 1013);

for (const probe of ['function $e(', 'var b = 1e-7', 'function ct(', 'function st(']) {
  if (!geometry.includes(probe) && !tiling.includes(probe)) {
    throw new Error(`missing ${probe}, adjust the slice range`);
  }
}

const exports = `
export const GRID_TABLE = Je.map(([id, name]) => ({ id, name }));
export const REFIT_TABLE = Ye;
export function guidesFor(id, original = false) {
  const table = original ? W : G;
  return table.find((g) => g.id === id)?.guides ?? null;
}
export const FREE_IDS = new Set([
  'square-16', 'inscribed-squares', 'weave', 'diagonal', 'triangles',
  'trefoil', 'halo', 'compass', 'isometric',
]);
export const DERIVED_IDS = new Set([
  'cross-tiling', 'quadtree', 'petals', 'trihexagonal', 'chevron', 'spiral',
]);
export { $e as cellsFor };
export { Be as scaleYFor, st as tilesCovering, ct as tileTransform };
`;

fs.writeFileSync(OUT, `// Generated by extract.mjs, do not edit.\n${geometry}\n${tiling}\n${exports}`);
console.log(`wrote ${OUT}`);
